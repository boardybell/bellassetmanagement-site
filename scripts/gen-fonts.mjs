// Generates src/styles/fonts.css: @font-face rules plus metrics-matched local fallbacks
// (size-adjust, ascent/descent/line-gap overrides) so swapping to the web font does not reflow.
import { fromBuffer } from '@capsizecss/unpack';
import { readFileSync } from 'node:fs';
import { createFontStack } from '@capsizecss/core';
import georgia from '@capsizecss/metrics/georgia';
import timesNewRoman from '@capsizecss/metrics/timesNewRoman';
import arial from '@capsizecss/metrics/arial';
import { writeFileSync } from 'node:fs';

const faces = [
  { family: 'Playfair Display', file: 'PlayfairDisplay-400.woff2', weight: 400, fb: [georgia, timesNewRoman] },
  { family: 'Playfair Display', file: 'PlayfairDisplay-500.woff2', weight: 500 },
  { family: 'Source Serif 4', file: 'SourceSerif4-400.woff2', weight: 400, fb: [georgia, timesNewRoman] },
  { family: 'Source Serif 4', file: 'SourceSerif4-500.woff2', weight: 500 },
  { family: 'IBM Plex Sans', file: 'IBMPlexSans-500.woff2', weight: 500, fb: [arial] },
];
let css = '/* Generated by scripts/gen-fonts.mjs. Do not edit by hand. */\n';
for (const f of faces) {
  css += `@font-face{font-family:'${f.family}';font-style:normal;font-weight:${f.weight};font-display:swap;src:url('../fonts/${f.file}') format('woff2');}\n`;
}
for (const f of faces.filter((x) => x.fb)) {
  const m = await fromBuffer(readFileSync(`src/fonts/${f.file}`));
  const { fontFaces } = createFontStack([{ familyName: f.family, ...m }, ...f.fb], { fontFaceFormat: 'styleString' });
  css += fontFaces.replace(/\n\s*/g, '') + '\n';
}
writeFileSync('src/styles/fonts.css', css);
